#!/usr/bin/env python3
"""Check that a review round's posts have the shape the review skill asks for.

`code-review-skill` §3 and §6 fix how a round is posted, because the implementer's
skill and the maintainer's phone both read it that way: a review body headed
``## Round <n> · <verdict>`` with one attribution line under it and the collapsed
``Measured this round`` list at its end; every inline finding and reply headed
``### K<n> · ...``; the attribution footer on every post; and no table anywhere.

This reads one JSON object on stdin and writes one on stdout::

    {"round": 2, "reviewer": "claude[bot]",
     "issue_comments": [...], "reviews": [...], "review_comments": [...]}
    -> {"misses": ["inline comment 123 has no `### K<n> ·` heading", ...]}

The three lists are the pull request's, as the REST API returns them. The round's posts
are the reviewer's ones after the workflow's last closing comment (a round or attempt
marker), so earlier rounds are not checked again; a top-level comment counts only when
it opens like a review post, since other answers share the reviewer's login. `scripts/review_loop_close.sh` passes
the misses to the gate, which lists them in the closing comment, and the round marker
carries their count for `scripts/review_tally.py`. A miss is a reviewer defect to fix
in the skill or the prompt; it never changes the verdict.
"""

from __future__ import annotations

import json
import re
import sys

WORKFLOW = "github-actions[bot]"
MARKERS = ("<!-- archivey-review-round", "<!-- archivey-review-attempt")
FOOTER = "_Generated by [Claude Code](https://claude.ai/code)_"

_FINDING_HEADING = re.compile(r"### K\d+ · ")
_TABLE_RULE = re.compile(r"^\s*\|?\s*:?-{3,}:?\s*(\|\s*:?-{3,}:?\s*)+\|?\s*$")
#: A GitHub API error pasted into a post, as a failed inline comment once left one.
_API_ERROR = re.compile(r'\{\s*"message":\s*"[^"]*",\s*"(errors|documentation_url)"')
_MEASURED = re.compile(r"<details>\s*<summary>[^<]*Measured this round")
#: How a top-level post shows it is part of a review rather than another answer by
#: the same bot login (the `@claude` assistant posts as it too).
_REVIEW_POST = re.compile(r"(## Round \d+ · |### K\d+ · )")


def _when(post: dict) -> str:
    return str(post.get("submitted_at") or post.get("created_at") or "")


def _outside_code(body: str) -> list[str]:
    """The lines outside code fences. An unclosed fence counts as no fence, so a stray
    one cannot hide the rest of a post from the checks."""
    all_lines = body.splitlines()
    fences = sum(line.lstrip().startswith("```") for line in all_lines)
    if fences % 2:
        return all_lines
    lines, fenced = [], False
    for line in all_lines:
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if not fenced:
            lines.append(line)
    return lines


def _common(what: str, body: str) -> list[str]:
    misses = []
    if not body.rstrip().endswith(FOOTER):
        misses.append(f"{what} does not end with the attribution footer")
    lines = _outside_code(body)
    if any(_TABLE_RULE.match(line) for line in lines):
        misses.append(f"{what} has a table")
    # Fenced or not: an API error has no place in a review post.
    if _API_ERROR.search(body):
        misses.append(f"{what} carries a GitHub API error message")
    return misses


def check(event: dict) -> list[str]:
    rnd = int(event.get("round") or 0)
    reviewer = str(event.get("reviewer") or "claude[bot]")

    def login(post: dict) -> str:
        return str((post.get("user") or {}).get("login") or "")

    closes = [
        _when(c)
        for c in event.get("issue_comments") or []
        if login(c) == WORKFLOW
        and (c.get("body") or "").startswith(MARKERS)
        and _when(c) < str(event.get("until") or "~")
    ]
    since = max(closes, default="")

    # `until` bounds the round when checking one after the fact.
    until = str(event.get("until") or "~")

    def this_round(posts: list[dict] | None) -> list[dict]:
        return [
            p for p in posts or [] if login(p) == reviewer and since < _when(p) < until
        ]

    bodies = [
        r for r in this_round(event.get("reviews")) if (r.get("body") or "").strip()
    ]
    bodies += [
        c
        for c in this_round(event.get("issue_comments"))
        if _REVIEW_POST.match(c.get("body") or "")
    ]
    inline = this_round(event.get("review_comments"))

    misses: list[str] = []
    head = f"## Round {rnd} · "
    main = [b for b in bodies if (b.get("body") or "").startswith(head)]
    if not main:
        misses.append(f"no review body headed `{head.strip()}`")
    for b in main[:1]:
        body = b.get("body") or ""
        rest = [line for line in body.splitlines()[1:] if line.strip()]
        if not rest or not rest[0].startswith("**Claude Code** · "):
            misses.append("the review body has no attribution line under its heading")
        if not _MEASURED.search(body):
            misses.append("the review body has no collapsed `Measured this round` list")
    for b in bodies:
        name = "the review body" if b in main[:1] else f"top-level post {b.get('id')}"
        misses += _common(name, b.get("body") or "")
    for c in inline:
        body = c.get("body") or ""
        kind = "reply" if c.get("in_reply_to_id") else "inline finding"
        if not _FINDING_HEADING.match(body):
            misses.append(f"{kind} {c.get('id')} has no `### K<n> ·` heading")
        misses += _common(f"{kind} {c.get('id')}", body)
    return misses


def main() -> int:
    event = json.load(sys.stdin)
    json.dump({"misses": check(event)}, sys.stdout)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
